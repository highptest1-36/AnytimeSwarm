"""Flat, self-contained submission folder ../AST_submission: one main.tex without \\input (numbers, tables and the
references to the supplementary material written out), the class files, the figures named Figure_1 ... and the
other submission files, all at one level. Run from the overleaf folder after a full build of main and supplementary:
python _build/flatten.py"""
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
OUT = HERE.parents[0] / "AST_submission"
FIGS = {"fig_overview": "Figure_1", "fig_errstructure": "Figure_2", "fig_tierc": "Figure_3",
        "fig_demo_gazebo": "Figure_4a", "fig_demo_tracks": "Figure_4b", "fig_s4c": "Figure_5",
        "fig_s5": "Figure_6", "fig_s6": "Figure_7", "fig_s7": "Figure_8"}

# number macros
vals = {}
for f in (HERE / "tables").glob("numbers*.tex"):
    for m in re.finditer(r"\\csname v(\w+)\\endcsname\{([^}]*)\}", f.read_text(encoding="utf-8")):
        vals[m.group(1)] = m.group(2)
for f in (HERE / "tables").glob("static_numbers*.tex"):
    for m in re.finditer(r"\\csname v(\w+)\\endcsname\{([^}]*)\}", f.read_text(encoding="utf-8")):
        vals[m.group(1)] = m.group(2)
# labels of the supplementary material
slab = {m.group(1): m.group(2) for m in
        re.finditer(r"\\newlabel\{([^}]*)\}\{\{([^}]*)\}", (HERE / "supplementary.aux").read_text(encoding="utf-8"))}

tex = (HERE / "main.tex").read_text(encoding="utf-8")
tex = re.sub(r"\\externaldocument\[S-\]\{supplementary\}[^\n]*\n", "", tex)

# tables written out
def table(m):
    t = (HERE / "tables" / f"{m.group(1)}.tex").read_text(encoding="utf-8")
    t = "\n".join(ln for ln in t.split("\n") if not ln.startswith("% generated"))
    return "\\begingroup\\uprighttext\n" + t.strip() + "\n\\endgroup"
tex = re.sub(r"\\inputtable\{(\w+)\}", table, tex)

# numbers written out
missing = set()
def val(m):
    if m.group(1) not in vals:
        missing.add(m.group(1))
        return m.group(0)
    return vals[m.group(1)]
tex = re.sub(r"\\val\{(\w+)\}", val, tex)
if missing:
    raise SystemExit(f"missing values: {missing}")

# references to the supplementary material written out
def sref(m):
    if m.group(1) not in slab:
        raise SystemExit(f"unknown supplementary label {m.group(1)}")
    return slab[m.group(1)]
tex = re.sub(r"\\ref\{S-([^}]*)\}", sref, tex)

# figures by their submission names, in the same folder
for old, new in FIGS.items():
    tex = tex.replace(r"\fig{" + old + "}", r"\fig{" + new + "}")
tex = tex.replace(r"\includegraphics{figures/#1.pdf}", r"\includegraphics{#1.pdf}")

# preamble: no cross-document references, no number files
tex = tex.replace("\\usepackage{xr-hyper}\n", "")
tex = re.sub(r"\\externaldocument\[S-\]\{supplementary\}[^\n]*\n", "", tex)
tex = re.sub(r"\\makeatletter\n\\@for\\@numfile:=.*?\\makeatother\n", "", tex, flags=re.S)
tex = re.sub(r"\\newcommand\{\\val\}[^\n]*\n", "", tex)
tex = re.sub(r"\\newcommand\{\\inputtable\}[^\n]*\n", "", tex)
tex = tex.replace("% Every number in the text is a macro from tables/numbers*.tex (generated by the experiment scripts); none is typed\n% by hand.\n", "")
# drop full-line source comments (build notes, internal paths); keep only the GenAI-declaration placeholder
KEEP = ("Declaration of generative AI", "to be written by the authors")
tex = "\n".join(l for l in tex.split("\n")
                if not (l.lstrip().startswith("%") and not any(k in l for k in KEEP)))
tex = re.sub(r"\n{3,}", "\n\n", tex)
assert "\\input{" not in tex and "tables/" not in tex, "leftover input"

if OUT.exists():
    shutil.rmtree(OUT)
OUT.mkdir()
header = ("% Chance Constraints as Effective Deadlines for Fast Replanning of UAV Fleets Under Uncertainty.\n"
          "% Manuscript for Aerospace Science and Technology (Elsevier, cas-dc template).\n"
          "% Compile: pdflatex main.tex (twice). All files are in this folder.\n")
(OUT / "main.tex").write_text(header + tex, encoding="utf-8", newline="\n")
shutil.copy(HERE / "cas-dc.cls", OUT / "cas-dc.cls")
# the class takes its e-mail icon from thumbnails/; in the flat folder the icon sits next to the class file
sty = (HERE / "cas-common.sty").read_text(encoding="utf-8").replace("{thumbnails/cas-", "{cas-")
(OUT / "cas-common.sty").write_text(sty, encoding="utf-8", newline="\n")
shutil.copy(HERE / "thumbnails" / "cas-email.jpeg", OUT / "cas-email.jpeg")
for old, new in FIGS.items():
    shutil.copy(HERE / "figures" / f"{old}.pdf", OUT / f"{new}.pdf")
shutil.copy(HERE / "supplementary.pdf", OUT / "Supplementary_material.pdf")
print("written", OUT)
