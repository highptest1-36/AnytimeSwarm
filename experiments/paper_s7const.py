"""Study 7a with a score that matches the fixed-cost rule exactly (review round 2, comment 1; no new runs).

The fixed-cost rule charges every late arrival c_j = lam w_bar with w_bar = 2.1, the mean reward of the generator, because
the planner cannot know the total reward W of a mission while tasks are still arriving. The score u_lam = U - lam n_late/n
of studies 5-7 instead charges lam W/n, the realised mean reward of the mission. This script reports how far W/n varies
over the held-out missions and repeats the study 7a comparisons with the score that charges exactly lam w_bar,
    u'_lam = U - lam w_bar n_late / W,
so that the decision rule and the score use the same cost. Statistics as in experiments/analyze_study7.py.

    python experiments/paper_s7const.py  ->  paper_journal/tables/numbers_s7c.tex (macros \\val{UC...}),
                                             paper_journal/tables/tab_s7const.tex, results/study7/report_const.md
"""
import pandas as pd

import analyze_study7 as a7
from analyze_study4 import noninf, paired, sup

W_BAR = 2.1
LAMS = {0.5: "Half", 1.0: "One", 2.0: "Two"}


def fmt(m, lo, hi):
    return f"{m * 100:+.2f} [{lo * 100:+.2f}, {hi * 100:+.2f}]".replace("-", "$-$")


def main():
    df = pd.read_csv(a7.TB / "s7a_heldout_B.csv")
    mis = df.groupby("scenario").agg(W=("reward_total", "first"), n=("n_tasks", "first"))
    wn = mis.W / mis.n
    mac = {"UCWnMean": f"{wn.mean():.2f}", "UCWnSd": f"{wn.std():.2f}", "UCWnMin": f"{wn.min():.2f}",
           "UCWnMax": f"{wn.max():.2f}", "UCWnCv": f"{wn.std() / wn.mean() * 100:.0f}"}
    rep = ["# Study 7a with the exact fixed-cost score u'_lam = U - lam w_bar n_late / W", "",
           f"W/n over {len(mis)} missions: mean {wn.mean():.3f}, sd {wn.std():.3f}, range {wn.min():.2f}-{wn.max():.2f}",
           "", "| lam | comparison | u_lam (study 7a) | u'_lam (exact) |", "|---|---|---|---|"]
    rows = []
    for lam, key in LAMS.items():
        x0 = a7.score(df, lam, "fee")
        x0 = pd.concat([x0, a7.tuned(x0, "fee", lam, "Prop")], ignore_index=True)
        x1 = df.assign(u=df.utility_rate - lam * W_BAR * df.late_served / df.reward_total)
        x1 = pd.concat([x1, a7.tuned(x1, "fee", lam, "Prop")], ignore_index=True)
        for cname, b in (("CAprop", a7.ca(lam, "prop")), ("Prop", f"Prop@fee{lam:g}")):
            r0 = sup(paired(x0, a7.ca(lam, "fee"), b, "u"))
            r1 = sup(paired(x1, a7.ca(lam, "fee"), b, "u"))
            mac[f"UCD{cname}{key}"] = fmt(*r1[:3])
            mac[f"UCDabs{cname}{key}"] = f"{abs(r1[0]) * 100:.2f}"
            mac[f"UCP{cname}{key}"] = "$<$0.001" if r1[3] < 0.001 else f"{r1[3]:.3f}"
            if cname == "Prop":
                ni = noninf(paired(x1, a7.ca(lam, "fee"), b, "u"))
                mac[f"UCPNI{cname}{key}"] = "$<$0.001" if ni[3] < 0.001 else f"{ni[3]:.3f}"
            lab = "fixed-cost vs.\\ proportional rule" if cname == "CAprop" else "fixed-cost rule vs.\\ tuned buffer"
            rows.append((lam, lab, fmt(*r0[:3]), fmt(*r1[:3]), r1[3]))
            rep.append(f"| {lam:g} | {cname} | {r0[0] * 100:+.2f} [{r0[1] * 100:+.2f}, {r0[2] * 100:+.2f}] | "
                       f"{r1[0] * 100:+.2f} [{r1[1] * 100:+.2f}, {r1[2] * 100:+.2f}] p={r1[3]:.4f} |")
    (a7.OUT / "report_const.md").write_text("\n".join(rep) + "\n", encoding="utf-8")
    print("\n".join(rep))
    with open(a7.P / "tables" / "numbers_s7c.tex", "w", encoding="utf-8") as fh:
        fh.write("% generated by experiments/paper_s7const.py -- do not edit\n")
        for k, v in sorted(mac.items()):
            fh.write(f"\\expandafter\\def\\csname v{k}\\endcsname{{{v}}}\n")
    pv = lambda p: "$<$0.001" if p < 0.001 else f"{p:.3f}"
    lines = ["% generated by experiments/paper_s7const.py -- do not edit",
             "\\begin{table}[t]",
             "\\caption{Study~7a, held-out seeds 13000--13029: the fixed-cost rule scored with $u_\\lambda$, which "
             "charges a late arrival the realised mean reward $W/n$ of the mission, and with "
             "$u'_\\lambda=U-\\lambda\\bar w\\,n_{\\mathrm{late}}/W$, which charges exactly the cost $\\lambda\\bar w$ "
             "that the rule assumes. Differences in pp with 95\\% paired bootstrap intervals over 270 missions; $p$ for "
             "$u'_\\lambda$.}\\label{tab:Ss7const}",
             "\\centering\\footnotesize", "\\setlength{\\tabcolsep}{2.5pt}",
             "\\begin{tabular}{@{}clllr@{}}", "\\toprule",
             "$\\lambda$ & Comparison & $u_\\lambda$ & $u'_\\lambda$ & $p$ \\\\", "\\midrule"]
    for lam, lab, a, b, p in rows:
        lines.append(f"{lam:g} & {lab} & {a} & {b} & {pv(p)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (a7.P / "tables" / "tab_s7const.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
