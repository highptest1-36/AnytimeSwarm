"""Descriptive extras for study 3, written after the held-out run (not part of the frozen analysis).

The frozen analysis (experiments/analyze_study3.py) computes every test of docs/10_PROTOCOL_V3.md. This script only adds
descriptive numbers for the text (relative gains, lost and skipped tasks) to tables/numbers_s3x.tex and redraws
figures/fig_s3.pdf with the same bootstrap intervals and corrected labels.
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

import analyze_study2 as a2
import analyze_study3 as a3
from analyze_study2 import boot

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "paper_journal"
MAC = {}


def main():
    df = pd.read_csv(ROOT / "results" / "tier_b" / "s3_heldout_B.csv")
    M = a3.methods("proposed~fb=nominal+periodic:60")
    g = df.groupby("method").agg(u=("utility_rate", "mean"), late=("late_served", "mean"),
                                 lost=("dropped_by_delay", "mean"), skip=("dropped_in_exec", "mean"),
                                 served=("served", "mean"))
    fb = g.loc[M["FB"][0]]
    for k, (spec, _) in M.items():
        r = g.loc[spec]
        MAC[f"LLost{k}"] = f"{r.lost:.2f}"
        MAC[f"LSkip{k}"] = f"{r.skip:.2f}"
        MAC[f"LServed{k}"] = f"{r.served:.1f}"
        if k != "FB":
            MAC[f"LURel{k}"] = f"{(fb.u / r.u - 1) * 100:.1f}"
    MAC["LLateIncProp"] = f"{(fb.late / g.loc[M['Prop'][0], 'late'] - 1) * 100:.0f}"
    MAC["LLateRedForty"] = f"{(1 - fb.late / g.loc[M['Forty'][0], 'late']) * 100:.0f}"
    out = ["% generated by experiments/paper_study3_extras.py -- do not edit"]
    out += [f"\\expandafter\\def\\csname v{k}\\endcsname{{{v}}}" for k, v in sorted(MAC.items())]
    (P / "tables" / "numbers_s3x.tex").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    labels = {"Prop": "vs. proposed (study 2)", "Buf": "vs. constant 60 s buffer", "Forty": "vs. ALNS, fixed 40 ms",
              "Conv": "vs. conventional planner"}
    keys = list(labels)
    fig, ax = plt.subplots(figsize=(6.6, 2.9))
    width = 0.8 / len(keys)
    for j, k in enumerate(keys):
        for i, (xl, wf, _, _) in enumerate(a3.REGIMES):
            m, lo, hi, _ = boot(a3.paired(a3.regime(df, xl, wf), M["FB"][0], M[k][0]), n=4000)
            x = i + (j - (len(keys) - 1) / 2) * width
            ax.errorbar(x, m * 100, yerr=[[(m - lo) * 100], [(hi - m) * 100]], fmt="o", ms=4.5, capsize=2.5,
                        color=a2.COL[k], label=labels[k] if i == 0 else None)
    ax.axhline(0, color="black", lw=0.8)
    ax.set_xticks(range(len(a3.REGIMES)),
                  [f"{xl} disturbances\nwindows $\\times${wf:g}" for xl, wf, _, _ in a3.REGIMES])
    ax.set_ylabel("fallback minus method (pp)")
    ax.grid(axis="y", alpha=0.3)
    ax.legend(frameon=False, loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=2, handletextpad=0.3,
              columnspacing=1.5)
    fig.tight_layout()
    fig.savefig(P / "figures" / "fig_s3.pdf")
    plt.close(fig)


if __name__ == "__main__":
    main()
