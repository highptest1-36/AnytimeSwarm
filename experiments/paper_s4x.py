#!/usr/bin/env python3
"""Derived numbers for the study-4 text (prefix X): the margin implied by the calibrated error model at the selected z,
written as slope and intercept so that it can be compared with the tuned proportional buffer, and the spread of the
utility of the three lead-time-scaled models. Reads only frozen inputs and the generated numbers_s4.tex.

    python experiments/paper_s4x.py   ->  paper_journal/tables/numbers_s4x.tex
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TAB = ROOT / "paper_journal" / "tables"

import sys  # noqa: E402
sys.path.insert(0, str(ROOT))
from journal_core.study4 import PROP_BY_LEVEL, Z4_BY_LEVEL  # noqa: E402


def s4_macros() -> dict:
    out = {}
    for name, val in re.findall(r"\\csname v(\w+)\\endcsname\{([^}]*)\}", (TAB / "numbers_s4.tex").read_text()):
        out[name] = val
    return out


def main():
    em = json.loads((ROOT / "models" / "error_model_dev.json").read_text())
    vals = {}
    for lvl, key in (("mid", "Mid"), ("high", "High")):
        p, z = em[lvl], Z4_BY_LEVEL[lvl]
        vals[f"XSlope{key}"] = f"{p['b1'] + z * p['s1']:.2f}"
        vals[f"XIntercept{key}"] = f"{p['b0'] + z * p['s0']:.0f}"
        vals[f"XPropC{key}"] = f"{PROP_BY_LEVEL[lvl]:.2f}"
    q = s4_macros()
    us = [float(q[k]) for k in ("QUCC", "QUPropBuf", "QUMP")]
    vals["XRangeScaled"] = f"{max(us) - min(us):.2f}"
    # every difference "+m [lo, hi]" of numbers_s4.tex also as |m| (XDabs...) and as its interval (XCI...)
    for name, val in q.items():
        m = re.fullmatch(r"(\S+) \[(.+), (.+)\]", val)
        if name.startswith("QD") and m:
            num = lambda s: float(s.replace("$-$", "-"))  # noqa: E731
            tex = lambda x: f"{x:.2f}".replace("-", "$-$")  # noqa: E731
            vals["XDabs" + name[2:]] = f"{abs(num(m.group(1))):.2f}"
            vals["XCI" + name[2:]] = f"{tex(num(m.group(2)))} to {tex(num(m.group(3)))}"
    lines = ["% generated by experiments/paper_s4x.py -- do not edit"]
    lines += [f"\\expandafter\\def\\csname v{k}\\endcsname{{{v}}}" for k, v in sorted(vals.items())]
    (TAB / "numbers_s4x.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
