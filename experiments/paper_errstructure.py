"""Structure of the finish-time error on development missions: figure and numbers for the paper.

Reads results/tier_b/dev4_errstructure.json, dev4_errbins.csv, dev4_errpairs.csv and dev4_legs.csv
(experiments/b4_error_structure.py collect / analyse / legs) and writes
    paper_journal/figures/fig_errstructure.pdf   (a) spread of the error against the lead time with the three fits,
                                                 (b) spread of the flight-time error of single legs against their
                                                     nominal duration
    paper_journal/tables/numbers_err.tex         \\val macros (prefix E)
Only development seeds are used, so the analysis may be repeated at will.
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results" / "tier_b"
P = ROOT / "paper_journal"
LV = {"mid": "Mid", "high": "High"}
COL = {"mid": "C0", "high": "C3"}


def increment_corr(g):
    """Correlation of the error of a task with the error added by the next task of the same route and plan."""
    a, b = [], []
    for _, r in g.sort_values("f_plan").groupby(["uav", "t_pub"]):
        e = r.e.to_numpy()
        a += list(e[:-1])
        b += list(np.diff(e))
    return float(np.corrcoef(a, b)[0, 1]), len(a)


def main():
    js = json.loads((R / "dev4_errstructure.json").read_text())
    bins = pd.read_csv(R / "dev4_errbins.csv")
    pairs = pd.read_csv(R / "dev4_errpairs.csv")
    legs = pd.read_csv(R / "dev4_legs.csv")
    mp = json.loads((ROOT / "models" / "mp_model_dev.json").read_text())
    mac = {}
    for lv, L in LV.items():
        s = js[lv]
        mac[f"ENPairs{L}"] = f"{s['n_pairs']:,}".replace(",", "\\,")
        mac[f"EDAicSqrt{L}"] = f"{s['sqrt']['aic'] - s['affine']['aic']:.0f}"
        mac[f"EDAicHyb{L}"] = f"{s['hybrid']['aic'] - s['affine']['aic']:.0f}"
        mac[f"EDCvSqrt{L}"] = f"{(s['affine']['cv_loglik'] - s['sqrt']['cv_loglik']):.0f}"
        mac[f"EDCvHyb{L}"] = f"{(s['affine']['cv_loglik'] - s['hybrid']['cv_loglik']):.0f}"
        mac[f"EShareMission{L}"] = f"{100 * s['re']['share_between']:.0f}"
        c, n = increment_corr(pairs[pairs.level == lv])
        mac[f"EIncCorr{L}"] = f"{c:.2f}"
        mac[f"EIncN{L}"] = f"{n:,}".replace(",", "\\,")
        b = bins[bins.level == lv]
        last = b.iloc[-1]
        mac[f"ESdLate{L}"] = f"{last.sd_emp:.0f}"
        mac[f"ESdLateSqrt{L}"] = f"{last.sd_sqrt:.0f}"
        mac[f"ESdLateAff{L}"] = f"{last.sd_affine:.0f}"
        mac[f"EHLate{L}"] = f"{last.h_mean:.0f}"
        mac[f"EMpA{L}"] = f"{mp[lv]['a']:.2f}"
        mac[f"EMpCv{L}"] = f"{mp[lv]['cv']:.2f}"
        mac[f"EMpAs{L}"] = f"{mp[lv]['a_s']:.2f}"
        mac[f"EMpCvs{L}"] = f"{mp[lv]['cv_s']:.2f}"
        mac[f"EMpWait{L}"] = f"{100 * mp[lv]['share_wait']:.0f}"
    mac["ENMissions"] = str(js["mid"]["n_missions"])
    out = ["% generated by experiments/paper_errstructure.py -- do not edit"]
    out += [f"\\expandafter\\def\\csname v{k}\\endcsname{{{v}}}" for k, v in sorted(mac.items())]
    (P / "tables" / "numbers_err.tex").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))

    fig, ax = plt.subplots(1, 2, figsize=(6.6, 2.6))
    for lv, L in LV.items():
        b = bins[bins.level == lv]
        ax[0].plot(b.h_mean, b.sd_emp, "o", ms=4, color=COL[lv], label=f"{L} disturbances")
        h = np.linspace(b.h_mean.min(), b.h_mean.max(), 100)
        th = js[lv]
        a0, a1 = th["affine"]["theta"][2:]
        q0, q1 = th["sqrt"]["theta"][2:]
        ax[0].plot(h, a0 + a1 * h, "-", color=COL[lv], lw=1.4, label=f"{L}: $s_0+s_1h$")
        ax[0].plot(h, np.sqrt(q0 + q1 * h), "--", color=COL[lv], lw=1.2, label=f"{L}: $\\sqrt{{q_0+q_1h}}$")
        g = legs[(legs.level == lv) & (legs.t_nom > 1.0)]
        q = pd.qcut(g.t_nom, 10)
        m = mp[lv]
        res = g.t_act - (1 + m["a"]) * g.t_nom - m["c"]
        sd = res.groupby(q, observed=True).std()
        tm = g.t_nom.groupby(q, observed=True).mean()
        ax[1].plot(tm, sd, "o", ms=4, color=COL[lv], label=f"{L} disturbances")
        t = np.linspace(0, tm.max(), 50)
        ax[1].plot(t, m["cv"] * t, "-", color=COL[lv], lw=1.4)
    ax[0].set_xlabel("lead time $h$ (s)")
    ax[0].set_ylabel("sd of finish-time error (s)")
    ax[1].set_xlabel("nominal flight time of a leg $t$ (s)")
    ax[1].set_ylabel("sd of flight-time error (s)")
    for a, tag in zip(ax, "ab"):
        a.grid(alpha=0.3)
        a.set_title(f"({tag})", loc="left", fontsize=9)
    ax[0].plot([], [], "-", color="0.3", lw=1.4, label="affine, $s_0+s_1h$")
    ax[0].plot([], [], "--", color="0.3", lw=1.2, label=r"independent increments, $\sqrt{q_0+q_1h}$")
    ax[1].plot([], [], "-", color="0.3", lw=1.4, label="proportional, $c_v t$")
    ax[0].legend(frameon=False, fontsize=6.5, loc="upper left")
    ax[1].legend(frameon=False, fontsize=6.5, loc="upper left")
    fig.tight_layout()
    fig.savefig(P / "figures" / "fig_errstructure.pdf")
    plt.close(fig)


if __name__ == "__main__":
    main()
