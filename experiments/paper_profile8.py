"""Study 8, descriptive (docs/18_PROTOCOL_V8.md section 7): peak memory of a planning call, measured with tracemalloc on
development missions after the held-out runs. tracemalloc slows the planner, so it is not used in the timed runs, and
the number of iterations within the 40 ms budget is lower than in the timed runs; the peak is set by the planning
model and the solution copies, not by the number of iterations.

    python experiments/paper_profile8.py          # writes results/study8/profile_memory.md and macros numbers_s8m.tex

Missions: development seeds 0-2, large scale (20 UAVs, 140 tasks, the largest planning problems), three profiles,
exec high, latency high, kappa 50, windows 1. Per method the peak traced memory of each planning call (Python and
NumPy allocations) and the resident set size of the process at the end.
"""
import copy
import resource
import sys
import tracemalloc
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "experiments"))
from journal_core import ORIGINAL  # noqa: E402,F401
from journal_core import study4  # noqa: E402
from journal_core.execution import EXEC_LEVELS, LATENCY_LEVELS  # noqa: E402
from journal_core.kinematic_executor import run_mission_kin  # noqa: E402
from journal_core.risk import ErrorModel  # noqa: E402
from journal_core.study4 import load_mp  # noqa: E402
from journal_core.study7 import solve7  # noqa: E402

from anytimeswarm.simulator.scenario import generate_scenario  # noqa: E402
from anytimeswarm.utils import load_config  # noqa: E402

CFG = load_config(ORIGINAL / "configs" / "frozen_2026-10-24.yaml")
ERR = ErrorModel.load_all(ROOT / "models" / "error_model_dev.json")["high"]
METHODS = {"CAfee": {"z": study4.Z4_BY_LEVEL["high"], "lam": 1.0, "cost": "fee", "w_bar": 2.1},
           "CAprop": {"z": study4.Z4_BY_LEVEL["high"], "lam": 1.0},
           "MPCA": {"lam": 1.0, "mp": None, "z_mp": study4.ZMP_BY_LEVEL["high"]},
           "Prop": {"prop_nofb": 0.45},
           "Nom": {}}


def main():
    mp = load_mp()["high"]
    out = ["# Peak memory of a planning call (development missions, tracemalloc)", "",
           "Seeds 0-2, large scale, 3 profiles, exec high, kappa 50, windows 1; ALNS 40 ms per call.", "",
           "| method | calls | mean peak MB | max peak MB |", "|---|---|---|---|"]
    mac = []
    for key, kw in METHODS.items():
        kw = dict(kw)
        if "mp" in kw:
            kw["mp"] = mp
        peaks = []

        def solver(*a, **k):
            tracemalloc.reset_peak()
            r = solve7(*a, **k)
            peaks.append(tracemalloc.get_traced_memory()[1] / 2 ** 20)
            return r
        tracemalloc.start()
        for profile in CFG["profiles"]:
            for seed in range(3):
                sc = generate_scenario(CFG, "large", profile, seed)
                run_mission_kin(copy.deepcopy(sc), CFG, "alns_fixed", 40.0, kappa=50.0, xm=EXEC_LEVELS["high"],
                                lat=LATENCY_LEVELS["high"], seed=seed, trigger="periodic:60", solver=solver,
                                solve_kwargs={"err": ERR, **kw, "check": False})
        tracemalloc.stop()
        p = np.asarray(peaks)
        out.append(f"| {key} | {p.size} | {p.mean():.2f} | {p.max():.2f} |")
        mac.append((f"SMemMean{key}", f"{p.mean():.1f}"))
        mac.append((f"SMemMax{key}", f"{p.max():.1f}"))
    rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024
    out += ["", f"Resident set size of the process at the end: {rss:.0f} MB."]
    mac.append(("SMemRss", f"{rss:.0f}"))
    (ROOT / "results" / "study8").mkdir(parents=True, exist_ok=True)
    (ROOT / "results" / "study8" / "profile_memory.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    lines = ["% generated by experiments/paper_profile8.py -- do not edit"]
    lines += [f"\\expandafter\\def\\csname v{k}\\endcsname{{{v}}}" for k, v in mac]
    (ROOT / "paper_journal" / "tables" / "numbers_s8m.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
