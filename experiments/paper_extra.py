#!/usr/bin/env python3
"""Derived numbers for the manuscript (descriptive, no new runs, no new tests).

1. Practical units for study 5 (held-out, results/tier_b/s5_heldout_B.csv): per 100 tasks of a mission, the tasks served
   on time and late; the flight distance per mission and per task served on time; the share of arrivals that were late.
2. Outcome words for the study-6 rows of the hypothesis table (tables/tab_hyp.tex), from numbers_s6.tex.

    python experiments/paper_extra.py  ->  paper_journal/tables/numbers_extra.tex (macros \\val{Y...})
"""
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TAB = ROOT / "paper_journal" / "tables"
T, A = "+periodic:60", "alns_fixed@40~"
S5 = {"CA": [A + "z=auto4;lam=1" + T], "CCfb": [A + "z=auto4;fb=nominal" + T], "Forty": ["alns_fixed@40" + T],
      "Conv": ["alns_fixed@40+event"]}
# proportional buffer tuned for lambda = 1 (journal_core/study5.TUNED): c = 0.3 (mid) and 0.45 (high), no fallback
PROP1 = {"mid": A + "prop=0.3;fb=none" + T, "high": A + "prop=0.45;fb=none" + T}
MAC = {}


def put(k, v):
    MAC["Y" + k] = v


def practical():
    f = ROOT / "results" / "tier_b" / "s5_heldout_B.csv"
    if not f.exists():
        return
    d = pd.read_csv(f)
    groups = {k: d[d.method.isin(v)] for k, v in S5.items()}
    groups["Prop"] = pd.concat([d[(d.exec_level == l) & (d.method == m)] for l, m in PROP1.items()])
    for k, s in groups.items():
        put(f"OnTime{k}", f"{100 * (s.served / s.n_tasks).mean():.1f}")
        put(f"LateHundred{k}", f"{100 * (s.late_served / s.n_tasks).mean():.1f}")
        put(f"Km{k}", f"{s.distance_km.mean():.1f}")
        put(f"KmPerTask{k}", f"{(s.distance_km / s.served.clip(lower=1)).mean():.2f}")
        put(f"WastedShare{k}", f"{100 * (s.late_served / (s.served + s.late_served).clip(lower=1)).mean():.1f}")
        put(f"Tasks{k}", f"{s.n_tasks.mean():.1f}")
    for k in ("CCfb", "Forty", "Prop"):
        a, b = groups["CA"], groups[k]
        put(f"LateRed{k}", f"{100 * (1 - a.late_served.mean() / b.late_served.mean()):.0f}")
        put(f"OnTimeDiff{k}", f"{100 * ((a.served / a.n_tasks).mean() - (b.served / b.n_tasks).mean()):.1f}")


def outcomes():
    f = TAB / "numbers_s6.tex"
    if not f.exists():
        return
    w = dict(re.findall(r"\\csname v(\w+)\\endcsname\{([^}]*)\}", f.read_text(encoding="utf-8")))
    for name in ("CBBA", "CBBAModel", "MPFb", "MPNoFb"):
        h = w.get(f"WHolds{name}One")
        if h is not None:
            put(f"Out{name}One", "supported" if h == "yes" else "not supported")


def main():
    practical()
    outcomes()
    lines = ["% generated by experiments/paper_extra.py -- do not edit"]
    lines += [f"\\expandafter\\def\\csname v{k}\\endcsname{{{v}}}" for k, v in sorted(MAC.items())]
    (TAB / "numbers_extra.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
