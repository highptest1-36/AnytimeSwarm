"""Shared definitions of the tier C (PX4 SITL + Gazebo + ROS 2) stack.

Scenario scaling. A tier C mission is a tier B scenario generated by the conference generator (scale "gz": 3 UAVs,
15 tasks = 5 tasks per UAV as in the small scale) and rescaled by (S_X, S_T): lengths x S_X, times x S_T, speeds
x S_X/S_T, energy x S_X, hover cost x S_X/S_T, distance price / S_X. Every dimensionless ratio of the problem (flight
time / deadline window, service / window, energy / route length, objective weights) is preserved, so a tier C mission
is the same decision problem as its tier B counterpart, flown by quadrotors in a 1 km world. A planning delay of
tau ms in tier C must be compared with tier B at kappa_B = kappa_C / S_T.

Frames. Mission map frame: metres, x = East, y = North, depot at the map centre (as in the planner).
Gazebo world (ENU) = mission frame shifted so that the depot is the origin. PX4 local NED of UAV k has its origin at
the UAV's spawn point: north = y_gz - spawn_y, east = x_gz - spawn_x, down = -altitude.
"""
from __future__ import annotations

import copy
import sys
from pathlib import Path

JOURNAL = Path(__file__).resolve().parents[1]
if str(JOURNAL) not in sys.path:
    sys.path.insert(0, str(JOURNAL))

from journal_core import ORIGINAL  # noqa: E402,F401
from anytimeswarm.simulator.entities import Event, Scenario, Task, UAV  # noqa: E402
from anytimeswarm.simulator.scenario import generate_scenario  # noqa: E402
from anytimeswarm.utils import load_config  # noqa: E402

S_X, S_T = 0.1, 0.25
GZ_SCALE = {"n_uav": 3, "n_tasks": 15, "stream": 9}
FROZEN_CFG = ORIGINAL / "configs" / "frozen_2026-10-24.yaml"
SPAWN_SPACING_M = 4.0           # UAVs start on a line through the depot, 4 m apart (East axis)
ALT0_M, ALT_STEP_M = 12.0, 4.0  # UAV k cruises at ALT0 + k * ALT_STEP (vertical separation, no collision avoidance)
ACCEPT_RADIUS_M = 1.5           # waypoint reached (horizontal) when closer than this


def tier_c_config() -> dict:
    """Frozen conference config with the rescaled world and objective (used by the planner in tier C)."""
    cfg = load_config(FROZEN_CFG)
    c = copy.deepcopy(cfg)
    w = c["world"]
    for k in ("map_m", "hotspot_std_m"):
        w[k] = w[k] * S_X
    w["capacity_m"] = [v * S_X for v in w["capacity_m"]]
    w["speed_mps"] = [v * S_X / S_T for v in w["speed_mps"]]
    w["hover_m_per_s"] = w["hover_m_per_s"] * S_X / S_T
    for k in ("horizon_s",):
        w[k] = w[k] * S_T
    for k in ("service_s", "window_s", "announce_lead_s"):
        w[k] = [v * S_T for v in w[k]]
    c["objective"]["gamma"] = cfg["objective"]["gamma"] / S_X     # same distance price per map-diameter
    c["scales"] = {"gz": dict(GZ_SCALE)}
    return c


def gz_scenario(profile: str, seed: int) -> Scenario:
    """Tier B scenario of scale gz, rescaled to the tier C world (see module docstring)."""
    base = load_config(FROZEN_CFG)
    b = copy.deepcopy(base)
    b["scales"] = dict(b["scales"]) | {"gz": dict(GZ_SCALE)}
    sc = generate_scenario(b, "gz", profile, seed)
    cfg = tier_c_config()
    tasks = [Task(t.id, t.x * S_X, t.y * S_X, t.announce * S_T, t.release * S_T, t.deadline * S_T,
                  t.service * S_T, t.reward) for t in sc.tasks]
    uavs = [UAV(u.id, u.x * S_X, u.y * S_X, u.speed * S_X / S_T, u.capacity * S_X) for u in sc.uavs]
    events = []
    for e in sc.events:
        d = dict(e.data)
        if e.kind == "deadline":
            d["new_deadline"] = d["new_deadline"] * S_T
        events.append(Event(e.time * S_T, e.kind, d))
    depot = (sc.depot[0] * S_X, sc.depot[1] * S_X)
    return Scenario(f"gz-{profile}-{seed}", seed, "gz", profile, depot, uavs, tasks, events, cfg["world"],
                    cfg["objective"])


def spawn_xy(k: int, n: int) -> tuple[float, float]:
    """Gazebo ENU spawn position of UAV k (depot = origin)."""
    return ((k - (n - 1) / 2.0) * SPAWN_SPACING_M, 0.0)


def altitude(k: int) -> float:
    return ALT0_M + ALT_STEP_M * k


def map_to_gz(x: float, y: float, depot) -> tuple[float, float]:
    return x - depot[0], y - depot[1]


def gz_to_map(x: float, y: float, depot) -> tuple[float, float]:
    return x + depot[0], y + depot[1]
